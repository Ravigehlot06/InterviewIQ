"""
generate_demo_dataset.py
-------------------------
Generates backend/ml/data/interview_performance.csv - a SYNTHETIC / DEMO
dataset used to train the initial readiness model before enough real
interview data has been collected in production.

This file exists so the ML pipeline is runnable and explainable from a
clean checkout. Once real PerformanceMetric rows accumulate in the
database, replace this dataset with a real export (see docs/ML.md).

Run:
    python backend/ml/generate_demo_dataset.py
"""
import os
import numpy as np
import pandas as pd

RNG = np.random.default_rng(seed=42)
N = 1200

DIFFICULTIES = ["easy", "medium", "hard"]
EXPERIENCE_LEVELS = ["fresher", "0-2", "2-5", "5+"]
INTERVIEW_TYPES = ["hr", "technical", "role_based", "company"]


def _readiness_label(overall_score: float) -> str:
    if overall_score >= 80:
        return "Interview Ready"
    if overall_score >= 60:
        return "Almost Ready"
    if overall_score >= 40:
        return "Needs Practice"
    return "Early Stage"


def generate():
    rows = []
    for _ in range(N):
        experience = RNG.choice(EXPERIENCE_LEVELS, p=[0.35, 0.30, 0.20, 0.15])
        difficulty = RNG.choice(DIFFICULTIES, p=[0.3, 0.45, 0.25])
        interview_type = RNG.choice(INTERVIEW_TYPES)

        # Experience shifts the baseline skill distribution upward.
        exp_bonus = {"fresher": 0, "0-2": 6, "2-5": 14, "5+": 20}[experience]
        difficulty_penalty = {"easy": 5, "medium": 0, "hard": -8}[difficulty]

        base = RNG.normal(55, 15) + exp_bonus + difficulty_penalty

        technical = np.clip(base + RNG.normal(0, 8), 0, 100)
        communication = np.clip(base + RNG.normal(5, 10), 0, 100)
        problem_solving = np.clip(base + RNG.normal(-2, 9), 0, 100)
        confidence = np.clip(base + RNG.normal(3, 12), 0, 100)
        answer_quality = np.clip((technical + communication) / 2 + RNG.normal(0, 6), 0, 100)
        questions_answered = int(np.clip(RNG.normal(6, 2), 3, 10))
        overall = np.clip(
            0.35 * technical + 0.25 * communication + 0.25 * problem_solving + 0.15 * answer_quality,
            0, 100,
        )

        rows.append({
            "technical_score": round(technical, 1),
            "communication_score": round(communication, 1),
            "problem_solving_score": round(problem_solving, 1),
            "confidence_score": round(confidence, 1),
            "answer_quality": round(answer_quality, 1),
            "questions_answered": questions_answered,
            "overall_score": round(overall, 1),
            "difficulty": difficulty,
            "experience_level": experience,
            "interview_type": interview_type,
            "readiness_label": _readiness_label(overall),
        })

    df = pd.DataFrame(rows)
    out_dir = os.path.join(os.path.dirname(__file__), "data")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "interview_performance.csv")

    header_comment = (
        "# DEMO / SYNTHETIC DATA - generated by generate_demo_dataset.py\n"
        "# This is NOT real user data. Replace with a real export once\n"
        "# enough production PerformanceMetric rows are available.\n"
    )
    with open(out_path, "w") as f:
        f.write(header_comment)
        df.to_csv(f, index=False)

    print(f"Wrote {len(df)} synthetic rows to {out_path}")


if __name__ == "__main__":
    generate()
